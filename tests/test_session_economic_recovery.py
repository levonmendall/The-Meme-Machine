    def test_descriptor_binding_collision_changed_bytes_and_commit_failure_refuse(self):
        descriptor = self.descriptor()
        for key, value in [('lower_slot', HEAD+1), ('upper_slot', HEAD+8),
                ('run_identity', 'a'*32), ('endpoint_identity', 'b'*64)]:
            with self.subTest(field=key):
                before = self.facts()
                with self.assertRaises(EvidenceUnavailable):
                    self.preserve(dict(descriptor, **{key: value}))
                self.assertEqual(self.facts(), before)
        before = self.facts()
        original_statement = self.state.writer._transaction_statement
        failure = sqlite3.OperationalError('offline-descriptor-commit-failure')
        def fail_commit(sql, phase):
            if phase == 'commit':
                raise failure
            return original_statement(sql, phase)
        with patch.object(self.state.writer, '_transaction_statement', side_effect=fail_commit):
            with self.assertRaises(sqlite3.OperationalError) as caught:
                self.preserve(descriptor)
        self.assertIs(caught.exception, failure)
        self.assertEqual(self.facts(), before)
        reference = self.preserve(descriptor)
        for raw in (canonical(dict(descriptor, upper_slot=HEAD+8)), canonical(descriptor)+' '):
            with self.subTest(tampered=raw[-5:]), self.changed_owner():
                self.db.execute('UPDATE acquisition_observations SET body=? WHERE id=?',
                    (raw, reference['observation_id']))
                with self.assertRaises(EvidenceUnavailable):
                    self.preserve(descriptor)
                self.refused(reference)
        with self.changed_owner():
            self.db.execute('INSERT INTO acquisition_observations(job,kind,at,body) VALUES(?,?,?,?)',
                (descriptor['failed_census_sha256'], 'source_economic_recovery_descriptor',
                    self.base.at, canonical(descriptor)))
            with self.assertRaises(EvidenceUnavailable):
                self.preserve(descriptor)
        self.assert_original_evidence()

