    def test_supplement_observation_hash_prefix_response_and_page_commit_are_required(self):
        reference = self.preserve()
        jobs, _ = self.recover()
        original = self.db.execute('SELECT result FROM acquisition_page_receipts WHERE job=? AND page=0',
            (jobs['pump'],)).fetchone()[0]
        supplement = json.loads(original)['archive_log_supplements'][0]
        observation = self.db.execute('SELECT body FROM acquisition_observations WHERE id=?',
            (supplement['observation_id'],)).fetchone()[0]
        self.assertTrue(self.verify(reference)['economic_interval_recovered'])
        cases = [
            ('DELETE FROM acquisition_observations WHERE id=?', (supplement['observation_id'],)),
            ("UPDATE acquisition_observations SET kind='other' WHERE id=?", (supplement['observation_id'],)),
            ("UPDATE acquisition_observations SET job='other' WHERE id=?", (supplement['observation_id'],)),
            ('UPDATE acquisition_page_receipts SET committed=0 WHERE job=?', (jobs['pump'],)),
        ]
        for sql, args in cases:
            with self.subTest(mutation=sql), self.changed_owner():
                self.db.execute(sql, args)
                self.refused(reference)
        for field, value in (('original_prefix_length', supplement['original_prefix_length']+1),
                ('endpoint_identity', 'b'*64), ('commitment', 'confirmed'),
                ('fetched_transaction_hash', 'b'*64), ('observation_body_hash', 'b'*64)):
            with self.subTest(receipt_field=field), self.changed_owner():
                body = json.loads(original)
                body['archive_log_supplements'][0][field] = value
                self.db.execute('UPDATE acquisition_page_receipts SET result=? WHERE job=? AND page=0',
                    (canonical(body), jobs['pump']))
                self.refused(reference)
        for mutate in ('prefix', 'logs', 'slot', 'endpoint'):
            with self.subTest(observation=mutate), self.changed_owner():
                body = json.loads(observation)
                if mutate == 'prefix':
                    body['original_prefix_length'] += 1
                elif mutate == 'logs':
                    body['response']['meta']['logMessages'][0] = 'unverified changed original prefix'
                elif mutate == 'slot':
                    body['response']['slot'] += 1
                else:
                    body['endpoint_identity'] = 'b'*64
                self.db.execute('UPDATE acquisition_observations SET body=? WHERE id=?',
                    (canonical(body), supplement['observation_id']))
                self.refused(reference)
        self.assert_original_evidence()

    def clean_session(self):
        source = SelectiveSource(SimpleNamespace(credential='offline', identity='a'*64), None)
        started = source.drain_snapshot()
        started.update(historical_unknown_handlers=2,
            historical_source_drain_sha256=self.base.incident.old_hash,
            historical_recovery_verified=False)
        ledger = self.value(drain.HANDLER_RECOVERY_KEY)
        raw = drain.begin_source_observation(self.state, self.old_source, started, handler_boundary=ledger)
        terminal = dict(json.loads(raw), state='DRAINED', terminal=True,
            terminal_at_monotonic=started['started_at_monotonic']+1)
        drain.publish_source_drain(self.state, self.old_source, terminal, handler_boundary=ledger,
            contained_observation=True, observation_boundary=raw)
        return terminal

    def test_buffered_tail_stays_unavailable_and_real_handoff_must_bound_it_completely(self):
        self.preserve();self.recover();self.clean_session()
        self.incident=self.interrupt(HEAD+40,buffered_tail=True)
        reference=self.preserve();_,proofs=self.recover()
        upper=self.incident['upper']
        facts=self.verify(reference)
        self.assertEqual((facts['descriptor']['tail_lower_slot'],
            facts['descriptor']['tail_upper_slot']),(upper+1,upper+124))
        self.assertTrue(facts['retained_economic_tail_unavailable'])
        self.assertFalse(facts['economic_tail_recovered'])
        self.clean_session()
        desired=[dict(family=family,scope=program_scope(family),rolling=True) for family in FAMILIES]
        with self.changed_owner():
            preserve_subscription_handoff(self.state,desired,upper+1)
            self.refused(reference)
        preserve_subscription_handoff(self.state,desired,upper+128)
        after=self.verify(reference)
        self.assertEqual(after['proof_ids'],proofs)
        self.assertTrue(after['retained_economic_tail_unavailable'])
